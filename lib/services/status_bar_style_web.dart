import 'dart:html' as html;

/// iOS даёт только 3 статичных варианта apple-mobile-web-app-status-bar-style
/// (default/black/black-translucent), без media-query. Переключаем сам тег в
/// момент смены темы: "black" (сплошной) на тёмной теме (почти совпадает с
/// #0A0A10 — минимальный шов), "default" (белый) на светлой (почти совпадает
/// с #F6F6FB). Каждая тема получает свой подходящий вариант вместо одного
/// компромисса на все случаи. Системное затемнение iOS поверх этой зоны
/// остаётся и не убирается (обсуждалось с владельцем 31.07.2026).
///
/// "black-translucent" здесь НЕ ИСПОЛЬЗУЕТСЯ и использоваться не должен — в
/// установленном на экран приложении он ломает попадание по кнопкам: контент
/// уезжает под часы, а координаты касания остаются от прежней рамки. Подробно
/// — в комментарии у самого тега в web/index.html.
///
/// Важно понимать границы этого кода: iOS читает тег при загрузке страницы, и
/// смена значения на лету, скорее всего, уже ничего не меняет в текущем
/// запуске. Настоящее значение для установленного приложения — то, что стоит
/// в web/index.html; здешнее переключение работает как уточнение при
/// следующем запуске, а не мгновенно.
class StatusBarStyle {
  static void apply(bool isDark) {
    final meta = html.document.querySelector(
      'meta[name="apple-mobile-web-app-status-bar-style"]',
    );
    meta?.setAttribute('content', isDark ? 'black' : 'default');
  }
}
