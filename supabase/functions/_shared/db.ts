/// Подключение к Postgres этого же проекта Supabase.
///
/// Почему прямой SQL, а не supabase-js поверх PostgREST: переносимый код —
/// это бывший SQLAlchemy, где половина запросов с составными условиями
/// (несколько фильтров + IS NULL + сортировка + каскадное удаление). Один в
/// один они ложатся на SQL, а на цепочки .eq().is().order() переписываются с
/// потерей читаемости и с риском тихо потерять условие — например фильтр
/// «не в корзине», который обязан стоять в каждом запросе к задачам.
import postgres from "npm:postgres@3";
import { env } from "./env.ts";

/// Строку подключения edge-функциям выдаёт сам Supabase (SUPABASE_DB_URL) —
/// класть её в секреты руками не нужно и не стоит: меньше мест, где лежит
/// пароль базы. DB_URL оставлен ручным переопределением на случай, если
/// придётся уйти на пулер Supavisor (IPv4, транзакционный режим).
const connectionString = env("DB_URL") || env("SUPABASE_DB_URL");

if (!connectionString) {
  throw new Error("Нет строки подключения к базе: ни DB_URL, ни SUPABASE_DB_URL");
}

export const sql = postgres(connectionString, {
  // Функция живёт короткими всплесками и может подниматься во множестве
  // экземпляров разом — держать по десятку соединений на каждый незачем.
  // Шесть, а не три: обработка сообщения боту занимает одно соединение
  // целиком на всё время (см. withChatLock) — при трёх четвёртый
  // одновременный чат остался бы вообще без соединения под свои запросы.
  max: 6,
  idle_timeout: 20,
  connect_timeout: 10,
  // Обязательно при работе через пулер в транзакционном режиме: там соединение
  // между запросами меняется, и подготовленные выражения не переживают
  // переключение. На прямом подключении флаг безвреден.
  prepare: false,
});

/// Условие «задача не в корзине» (C6).
///
/// Отдельной константой, а не копипастой по запросам: мест, где backend читает
/// задачи, пять — ассистент, правка задачи ассистентом, будильники, утренняя
/// сводка, кнопка «Готово» в боте. Забыть фильтр в одном из них означает, что
/// удалённая задача всплывёт напоминанием или в сводке, то есть корзина
/// окажется дырявой ровно там, где это заметнее всего.
///
/// Функция, а не константа: postgres.js возвращает из тега объект запроса со
/// своим состоянием, и один и тот же экземпляр, вставленный в два запроса
/// одновременно, — готовая гонка. Каждый вызов даёт свежий фрагмент.
export const notDeleted = () => sql`deleted_at is null`;
