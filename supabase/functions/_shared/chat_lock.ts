/// Сериализация обработки сообщений одного Telegram-чата.
///
/// Зачем: вебхук отвечает Telegram сразу, а обработка уходит в фон — значит
/// человек может прислать ВТОРОЕ сообщение, пока фон ещё разбирает первое. Если
/// первое ещё не записало свою правку в базу, второе («что у меня на сегодня?»
/// сразу после «добавь задачу на сегодня») не увидит её результат.
///
/// На FastAPI это решалось asyncio.Lock в памяти процесса. Здесь процесса нет:
/// каждый апдейт может попасть в свой экземпляр функции, и общей памяти у них
/// нет. Единственное, что у них общее — база, поэтому замок берём в ней:
/// консультативная блокировка Postgres видна всем экземплярам сразу и
/// освобождается сама, если экземпляр умрёт вместе с соединением.
///
/// Цена: соединение к базе занято на всё время обработки, включая вызов ИИ
/// (десятки секунд). Для бота с десятком пользователей это ничего не стоит; если
/// нагрузка вырастет, замок придётся делать не на соединении.
import { sql } from "./db.ts";

/// Сколько ждём своей очереди, прежде чем плюнуть и обработать без замка.
///
/// Потерять сообщение хуже, чем обработать его не по порядку: во втором случае
/// человек в редком случае увидит слегка устаревший список, в первом — полную
/// тишину в ответ.
const LOCK_WAIT_MS = 25_000;

export async function withChatLock<T>(
  chatId: string | number,
  fn: () => Promise<T>,
): Promise<T> {
  const key = String(chatId);
  const conn = await sql.reserve();
  let locked = false;
  try {
    try {
      // hashtext даёт из строки int4, которого pg_advisory_lock и ждёт.
      // lock_timeout распространяется и на консультативные блокировки, так что
      // вечного ожидания здесь быть не может.
      //
      // unsafe() потому, что SET не принимает параметры запроса — значение
      // приходится подставлять в текст. Подставляется собственная константа
      // модуля, ничего пользовательского сюда не попадает.
      await conn.unsafe(`set lock_timeout = ${LOCK_WAIT_MS}`);
      await conn`select pg_advisory_lock(hashtext(${key}))`;
      locked = true;
    } catch (e) {
      console.warn(`[telegram] не удалось взять замок чата ${key}, обрабатываю без него: ${e}`);
    }
    return await fn();
  } finally {
    try {
      if (locked) await conn`select pg_advisory_unlock(hashtext(${key}))`;
      // Соединение возвращается в общий пул, а lock_timeout мы меняли для всей
      // сессии — без сброса это значение утекло бы на чужие запросы.
      await conn.unsafe("reset lock_timeout");
    } catch (e) {
      // Не критично: блокировка всё равно снимется вместе с соединением.
      console.warn(`[telegram] не удалось прибраться после замка чата ${key}: ${e}`);
    }
    conn.release();
  }
}
