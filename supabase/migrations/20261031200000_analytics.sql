-- Аналитика использования Clarify (31.10.2026).
--
-- Зачем. Чтобы через месяц после запуска решать судьбу продукта по цифрам, а не
-- по ощущениям: сколько людей пришло, сколько задач они заводят в первую
-- неделю и сколько вернулось через неделю.
--
-- Что собирается. Только факт события, источник ввода и платформа — БЕЗ текста
-- задач, без устройств, без IP. Задачи считаются прямо по таблице tasks
-- (created_at/completed_at), поэтому в цифры попадают и задачи, созданные
-- сервером: ИИ, голос, Telegram-бот, MCP. Событие app_open нужно только для
-- активности: без него человек, который просто открывает список и отмечает
-- задачи, выглядел бы ушедшим.
--
-- Кто видит. Строки событий не читает никто, кроме функций ниже. Сводку
-- отдаёт analytics_summary() и только тем, кто внесён в analytics_admins.
--
-- Идемпотентно: файл можно прогонять повторно.

-- --- события ---------------------------------------------------------------

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  event text not null,
  props jsonb not null default '{}'::jsonb,
  platform text,
  app_version text,
  created_at timestamptz not null default now()
);

-- Набор событий закрыт: случайная опечатка в клиенте не должна плодить мусорные
-- категории, а новое событие — осознанное решение с правкой этого файла.
alter table public.analytics_events drop constraint if exists analytics_events_event_check;
alter table public.analytics_events add constraint analytics_events_event_check
  check (event in ('app_open', 'task_created'));

-- Защита от того, чтобы в props не начали складывать что-то крупное (а значит,
-- скорее всего, личное — текст задачи, например).
alter table public.analytics_events drop constraint if exists analytics_events_props_size_check;
alter table public.analytics_events add constraint analytics_events_props_size_check
  check (pg_column_size(props) <= 512);

create index if not exists analytics_events_event_created_idx on public.analytics_events (event, created_at);
create index if not exists analytics_events_user_created_idx on public.analytics_events (user_id, created_at);
create index if not exists tasks_created_at_idx on public.tasks (created_at);

alter table public.analytics_events enable row level security;

-- Писать можно только от своего имени. Политики на чтение нет СОЗНАТЕЛЬНО:
-- клиент свои события не читает, а сводку отдаёт функция ниже.
drop policy if exists analytics_events_insert_own on public.analytics_events;
create policy analytics_events_insert_own on public.analytics_events
  for insert to authenticated
  with check (user_id = auth.uid());

-- --- кто видит сводку --------------------------------------------------------

create table if not exists public.analytics_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- RLS без единой политики: таблицу не читает и не правит никто, кроме
-- security definer-функций и владельца базы.
alter table public.analytics_admins enable row level security;

create or replace function public.is_analytics_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.analytics_admins where user_id = auth.uid());
$$;

revoke all on function public.is_analytics_admin() from public, anon;
grant execute on function public.is_analytics_admin() to authenticated;

-- --- сводка ----------------------------------------------------------------
--
-- p_days — окно в днях (по умолчанию 30). Возвращает jsonb:
--   users_total, users_new                 — всего и новых за окно;
--   active_1d, active_7d, active_30d       — разные люди с любым действием;
--   tasks_created, tasks_completed         — задачи за окно (по таблице tasks);
--   first_week_tasks_avg                   — сколько задач в среднем заводит
--                                            новичок за первые 7 дней (только
--                                            те, кому уже есть 7 дней);
--   week1_cohort, week1_returned           — из пришедших за окно и проживших
--                                            неделю: сколько было активно на
--                                            8–14-й день;
--   sources                                — источники ввода из приложения;
--   platforms                              — открытия по платформам.
--
-- «Действие» = открыл приложение, завёл или закрыл задачу. Задачи учитываются
-- и те, что сделаны до появления этой аналитики, поэтому активность и возврат
-- считаются и по прошлому — пусть и без открытий приложения.

create or replace function public.analytics_summary(p_days integer default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  since timestamptz := now() - make_interval(days => greatest(p_days, 1));
  result jsonb;
begin
  if not public.is_analytics_admin() then
    raise exception 'not allowed' using errcode = '42501';
  end if;

  with activity as (
    select user_id, created_at as at from public.analytics_events
    union all
    select user_id, created_at from public.tasks where user_id is not null and created_at is not null
    union all
    select user_id, completed_at from public.tasks where user_id is not null and completed_at is not null
  ),
  cohort as (
    select id, created_at from auth.users
    where created_at >= since and created_at <= now() - interval '7 days'
  )
  select jsonb_build_object(
    'days', p_days,
    'users_total', (select count(*) from auth.users),
    'users_new', (select count(*) from auth.users where created_at >= since),
    'active_1d', (select count(distinct user_id) from activity where at >= now() - interval '1 day'),
    'active_7d', (select count(distinct user_id) from activity where at >= now() - interval '7 days'),
    'active_30d', (select count(distinct user_id) from activity where at >= now() - interval '30 days'),
    'tasks_created', (select count(*) from public.tasks where created_at >= since),
    'tasks_completed', (select count(*) from public.tasks where completed_at >= since),
    'first_week_tasks_avg', (
      select coalesce(round(avg(n), 1), 0) from (
        select (select count(*) from public.tasks t
                where t.user_id = c.id and t.created_at < c.created_at + interval '7 days') as n
        from cohort c
      ) s
    ),
    'week1_cohort', (select count(*) from cohort),
    'week1_returned', (
      select count(*) from cohort c
      where exists (
        select 1 from activity a
        where a.user_id = c.id
          and a.at >= c.created_at + interval '7 days'
          and a.at < c.created_at + interval '14 days'
      )
    ),
    'sources', coalesce((
      select jsonb_object_agg(src, n) from (
        select coalesce(props->>'source', 'other') as src, count(*) as n
        from public.analytics_events
        where event = 'task_created' and created_at >= since
        group by 1
      ) s
    ), '{}'::jsonb),
    'platforms', coalesce((
      select jsonb_object_agg(coalesce(platform, '?'), n) from (
        select platform, count(distinct user_id) as n
        from public.analytics_events
        where event = 'app_open' and created_at >= since
        group by 1
      ) p
    ), '{}'::jsonb)
  ) into result;

  return result;
end;
$$;

revoke all on function public.analytics_summary(integer) from public, anon;
grant execute on function public.analytics_summary(integer) to authenticated;
